const test = require('node:test');
const assert = require('node:assert/strict');
const { detectFileType } = require('../lib/fileType');

const createEmptyWav = () => Buffer.from([
  0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00,
  0x57, 0x41, 0x56, 0x45, 0x66, 0x6d, 0x74, 0x20,
  0x10, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00,
  0x44, 0xac, 0x00, 0x00, 0x88, 0x58, 0x01, 0x00,
  0x02, 0x00, 0x10, 0x00, 0x64, 0x61, 0x74, 0x61,
  0x00, 0x00, 0x00, 0x00
]);

test('detects audio with either supported file-type API shape', async () => {
  const result = await detectFileType(createEmptyWav());

  assert.equal(result?.ext, 'wav');
  assert.equal(result?.mime, 'audio/wav');
});
